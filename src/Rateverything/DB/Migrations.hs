module Rateverything.DB.Migrations
  ( applyPendingMigrations
  ) where

import Control.Monad (forM_, unless, void)
import Database.PostgreSQL.Simple

type SchemaVersion = Int

data Migration = Migration
  { version :: SchemaVersion
  , statements :: [Query]
  }

applyPendingMigrations :: Connection -> IO ()
applyPendingMigrations conn = do
  void $ execute_ conn "SET client_min_messages = warning"
  void $ execute_ conn "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)"
  appliedVersions <- map fromOnly <$> query_ conn "SELECT version FROM schema_migrations"
  forM_ migrationsInOrder $ \migration ->
    unless (migration.version `elem` appliedVersions) $
      applyMigration conn migration

applyMigration :: Connection -> Migration -> IO ()
applyMigration conn migration =
  withTransaction conn $ do
    mapM_ (execute_ conn) migration.statements
    void $ execute conn "INSERT INTO schema_migrations (version) VALUES (?)" (Only migration.version)

migrationsInOrder :: [Migration]
migrationsInOrder =
  [ Migration {version = 1, statements = schemaCarriedOverFromSqliteVersion}
  ]

schemaCarriedOverFromSqliteVersion :: [Query]
schemaCarriedOverFromSqliteVersion =
  [ createUsersTable
  , createCaseInsensitiveUniqueUsernameIndex
  , createSessionsTable
  , createCategoriesTable
  , createItemsTable
  , "CREATE INDEX items_category ON items(category_id)"
  , createReviewsTable
  , "CREATE INDEX reviews_item ON reviews(item_id)"
  , "CREATE INDEX reviews_user ON reviews(user_id)"
  , insertBuiltInCategories
  ]

createUsersTable :: Query
createUsersTable =
  "CREATE TABLE users (\
  \  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\
  \  username TEXT NOT NULL,\
  \  password_hash TEXT NOT NULL,\
  \  avatar_url TEXT,\
  \  created_at TIMESTAMPTZ NOT NULL DEFAULT now())"

createCaseInsensitiveUniqueUsernameIndex :: Query
createCaseInsensitiveUniqueUsernameIndex =
  "CREATE UNIQUE INDEX users_username_lower ON users (lower(username))"

createSessionsTable :: Query
createSessionsTable =
  "CREATE TABLE sessions (\
  \  token_hash TEXT PRIMARY KEY,\
  \  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,\
  \  created_at TIMESTAMPTZ NOT NULL DEFAULT now())"

createCategoriesTable :: Query
createCategoriesTable =
  "CREATE TABLE categories (\
  \  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\
  \  slug TEXT NOT NULL UNIQUE,\
  \  name TEXT NOT NULL,\
  \  description TEXT,\
  \  provider TEXT,\
  \  owner_id BIGINT REFERENCES users(id) ON DELETE CASCADE,\
  \  created_at TIMESTAMPTZ NOT NULL DEFAULT now())"

createItemsTable :: Query
createItemsTable =
  "CREATE TABLE items (\
  \  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\
  \  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,\
  \  title TEXT NOT NULL,\
  \  subtitle TEXT,\
  \  year INTEGER,\
  \  image_url TEXT,\
  \  description TEXT,\
  \  source TEXT NOT NULL,\
  \  external_id TEXT,\
  \  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,\
  \  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),\
  \  UNIQUE (source, external_id))"

createReviewsTable :: Query
createReviewsTable =
  "CREATE TABLE reviews (\
  \  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\
  \  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,\
  \  item_id BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,\
  \  rating INTEGER CHECK (rating BETWEEN 1 AND 10),\
  \  body TEXT,\
  \  liked BOOLEAN NOT NULL DEFAULT false,\
  \  consumed_on DATE,\
  \  created_at TIMESTAMPTZ NOT NULL DEFAULT now())"

insertBuiltInCategories :: Query
insertBuiltInCategories =
