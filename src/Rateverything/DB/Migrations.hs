-- | Database schema, applied incrementally at startup.
module Rateverything.DB.Migrations
  ( migrate
  ) where

import Control.Monad (forM_, unless, void)
import Database.PostgreSQL.Simple

-- | Applies every migration not yet recorded in @schema_migrations@.
migrate :: Connection -> IO ()
migrate conn = do
  void $ execute_ conn "SET client_min_messages = warning"
  void $ execute_ conn "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)"
  applied <- map fromOnly <$> query_ conn "SELECT version FROM schema_migrations"
  forM_ migrations $ \(version, statements) ->
    unless ((version :: Int) `elem` applied) $
      withTransaction conn $ do
        mapM_ (execute_ conn) statements
        void $ execute conn "INSERT INTO schema_migrations (version) VALUES (?)" (Only version)

